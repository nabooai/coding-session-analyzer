    deployed_to_prod: Mapped[int | None] = mapped_column(Integer)
    source: Mapped[str | None] = mapped_column(Text, server_default=text("'session'"))
    user: Mapped[str | None] = mapped_column(Text, server_default=text("'owner'"))
    harness: Mapped[str | None] = mapped_column(Text, server_default=text("'claude-code'"))
