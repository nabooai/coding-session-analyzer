Index("ix_actions_tid", actions.c.target_id)
Index("ix_actions_verb", actions.c.verb.collate("NOCASE"))   # so verb LIKE 'deploy%' uses it
Index("ix_relations_src", relations.c.source_id)
Index("ix_relations_tgt", relations.c.target_id)

Index("ix_served_session", served.c.session)
Index("ix_served_ref", served.c.ref, served.c.session)   # "how many OTHER sessions used this fact?": 7.5s -> 0.008s
Index("ix_queries_engine", queries.c.engine)
Index("ix_queries_session", queries.c.session)        # `queries` grows one row per prompt; never full-scan it
Index("ix_spans_trace", spans.c.trace_id)
Index("ix_spans_at", spans.c.at)                      # the retention DELETE keys on `at`
