class Fact(Base):
    """One durable fact (schema v2). THE sibling-task contract row: the
    resolution engine writes invalid_at/expired_at/state, registries-verify writes state, the
    taint/search tasks read all of it. Recompute rules live in store.refresh_facts — this model
    is the typed shape, not the lifecycle. `ref` = sha1(claim)[:12] content address."""
    __tablename__ = "facts"

    ref: Mapped[str] = mapped_column(Text, primary_key=True, nullable=True)
    claim: Mapped[str | None] = mapped_column(Text)
    type: Mapped[str | None] = mapped_column(Text)
    scope: Mapped[str | None] = mapped_column(Text)
    author: Mapped[str | None] = mapped_column(Text)       # FIRST asserting session's user
    domain: Mapped[str | None] = mapped_column(Text)       # code-home repo, else first session's project
    created_at: Mapped[str | None] = mapped_column(Text)   # system: first extraction (min mention date)
    valid_at: Mapped[str | None] = mapped_column(Text)     # world: became true (as_of can back-date)
    invalid_at: Mapped[str | None] = mapped_column(Text)   # world: stopped being true; NULL = current
    expired_at: Mapped[str | None] = mapped_column(Text)   # system: when we retired it
    state: Mapped[str | None] = mapped_column(Text, server_default=text("'extracted'"))
    confidence: Mapped[float | None] = mapped_column(REAL)  # owned by the resolve stage


class FactEdge(Base):
    """Durable fact->fact relation: supersedes|depends_on|contradicts|
    derived_from; `note` carries the resolution receipt. Never wiped by index passes."""
    __tablename__ = "fact_edges"

